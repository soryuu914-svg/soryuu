const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = {window:{}};
vm.runInNewContext(fs.readFileSync(__dirname + '/preview-template-store.js','utf8'),context);
const store = context.window.createPreviewTemplateStore();
const book = {id:'a',name:'第一本书'};
let people = [{id:'p1',name:'张三',summary:'旧简介',role:'主角',faction:'甲',fields:[['动机','寻找家人']]}];
let world = {地理:[{id:'w1',title:'旧城',kind:'城镇',summary:'旧设定',fields:[]}]};
store.syncBook(book,people,world);
assert.equal(store.list('characters').length,1);
assert.equal(store.list('world').length,1);
people[0].summary = '新简介'; people[0].goalMotivation = '要做什么：救回家人。为什么：家人被囚禁。'; people[0].fields[0][1] = '拯救家人'; world.地理[0].title = '新城';
store.syncBook(book,people,world);
assert.equal(store.list('characters')[0].card.summary,'新简介');
assert.equal(store.list('characters')[0].card.goalMotivation,people[0].goalMotivation);
assert.equal(store.list('characters')[0].card.fields[0][1],'拯救家人');
assert.equal(store.list('world')[0].card.title,'新城');
store.syncBook(book,[],{地理:[]});
assert.equal(store.list('characters')[0].linked,false);
assert.equal(store.list('world')[0].linked,false);
assert.equal(store.list('characters')[0].card.summary,'新简介');
assert.equal(store.list('world')[0].card.title,'新城');
assert.equal(store.list('characters')[0].card.goalMotivation,people[0].goalMotivation,'Deleting source retains goals and motives');
store.syncBook(book,[{...people[0],id:'p2'}],{地理:[]});
assert.equal(store.list('characters').length,2,'Same name does not merge stable source IDs');
store.syncBook({id:'b',name:'第二本书'},people,world);
assert.equal(store.list('characters').length,3,'Same card ID across books remains independent');
const copy = store.list('characters'); copy[0].card.name = '不应污染档案';
assert.ok(store.list('characters').every(item => item.card.name === '张三'));
const snapshot = store.snapshot(), revision = store.revision;
store.syncBook({id:'b',name:'第二本书'},[],world);
assert.equal(store.restore(snapshot,revision),false,'Undo must not overwrite later changes');
assert.equal(store.restore(snapshot,store.revision),true);
assert.equal(store.list('characters').find(item => item.bookId === 'b').linked,true);
console.log('Template lifecycle: create, update, delete retention, stable identity, isolation and guarded undo passed.');
vm.runInNewContext(fs.readFileSync(__dirname + '/preview-pages.js','utf8'),context);
const core = context.window.previewCardCore;
const projectedPerson = core.person(people[0]);
assert.equal(projectedPerson.faction,'甲');
assert.equal(projectedPerson.summary,'新简介');
assert.equal(projectedPerson.goalMotivation,people[0].goalMotivation);
assert.equal(projectedPerson.fields.length,0);
const projectedWorld = core.world(world.地理[0],'地理');
assert.equal(projectedWorld.kind,'地点');
assert.equal(projectedWorld.summary,'旧设定');
assert.equal(projectedWorld.fields.length,0);
const template = core.template({id:'t',title:'张三',kind:'人物模板',source:{type:'characters',card:people[0]}});
assert.ok(!('source' in template),'AI projection must not leak the full archived source object');
assert.deepEqual(Array.from(template.fields,field => field[0]),['身份','所属','目标与动机']);
console.log('Core card projections preserve facts and omit expanded fields and archive metadata.');
