const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const env = {window:{}};
vm.runInNewContext(fs.readFileSync(__dirname + '/preview-progression.js','utf8'),env);
vm.runInNewContext(fs.readFileSync(__dirname + '/preview-template-store.js','utf8'),env);
const model = env.window.previewProgression;
const hero = {id:'hero',name:'林逸',summary:'无灵根的少年',role:'主角',goalMotivation:'为救家人进入仙门。'};
const faction = {id:'faction',title:'青云宗',kind:'势力',summary:'南域顶级宗门'};
const change = (stage,chapter,value) => ({stage,chapter,title:'章节' + chapter,value,evidence:value,source:stage === 'actual' ? '正文' : '章纲'});
const planned = model.update(faction,change('planned',100,'青云宗将被灭门。'));
assert.equal(model.context(planned).currentState,faction.summary,'Plans cannot become current facts');
assert.equal(model.context(planned).plannedState,'青云宗将被灭门。');
const grown = model.update(hero,change('actual',100,'林逸突破金丹，为保护家人调查灭门幕后主使。'));
assert.equal(grown.summary,hero.summary,'Initial premise is retained');
assert.equal(grown.goalMotivation,hero.goalMotivation);
assert.ok(model.context(grown).currentState.includes('金丹'));
assert.equal(model.context(grown,99).currentState,hero.summary,'Earlier writing cannot see future facts');
assert.equal(model.context(grown,100).stateAsOf.chapter,100);
assert.throws(() => model.update(grown,change('actual',3,'林逸刚入仙门。')),/旧章节/);
assert.equal(grown.stateHistory.length,1);
const dead = model.update(planned,change('actual',100,'青云宗被灭，幸存弟子离散。'));
assert.ok(model.context(dead).currentState.includes('被灭'));
assert.equal(dead.plannedState,planned.plannedState,'Plans are not silently removed');
assert.equal(dead.stateHistory.length,2);
assert.equal(model.update(dead,change('actual',100,dead.currentState)).stateHistory.length,2,'Identical result is idempotent');
assert.throws(() => model.update(hero,change('actual',0,'坏章节')),/正确/);
assert.throws(() => model.update(hero,change('actual',100,'  ')),/正确/);
const suggestions = model.suggest([{type:'characters',card:hero},{type:'world',card:faction}],'林逸突破金丹。青云宗被灭。无关人离开。');
assert.equal(suggestions.length,2);
assert.ok(suggestions[0].evidence.includes('林逸'));
assert.equal(model.suggest([{type:'characters',card:hero}],'其他人突破。').length,0);
const store = env.window.createPreviewTemplateStore();
store.syncBook({id:'a',name:'甲书'},[grown],{势力:[dead]});
store.syncBook({id:'b',name:'乙书'},[hero],{势力:[faction]});
assert.ok(store.list('world').find(entry => entry.bookId === 'a').card.currentState.includes('被灭'));
assert.equal(store.list('world').find(entry => entry.bookId === 'b').card.currentState,undefined);
store.syncBook({id:'a',name:'甲书'},[],{势力:[]});
assert.equal(store.list('characters').find(entry => entry.bookId === 'a').card.stateHistory.length,1);
assert.equal(store.list('world').find(entry => entry.bookId === 'a').linked,false);
assert.ok(model.fields(dead).some(([label]) => label.includes('当前状态')));
// Exercise the real adoption bridge so a stale second card cannot leave the first half-updated.
const pagesSource = fs.readFileSync(__dirname + '/preview-pages.js','utf8');
const adoption = pagesSource.slice(pagesSource.indexOf('    applyProgression(batch) {'),pagesSource.indexOf('    getAIContext(view, group, bookId) {'));
const bookHero = {...hero}, bookFaction = {...faction}, archive = env.window.createPreviewTemplateStore();
const bridgeEnv = {window:env.window,activeBook:{id:'a',name:'甲书'},people:[bookHero],collections:{world:{groups:{势力:[bookFaction]}}},bookCards:new Map(),templateStore:archive,bookInfo:() => ({id:'a',name:'甲书'}),syncTemplates:() => {},resetSearch:() => {},renderPeople:() => {},renderCollection:() => {}};
const bridge = vm.runInNewContext('({' + adoption + '})',bridgeEnv);
const originalHero = JSON.stringify(bookHero), originalFaction = JSON.stringify(bookFaction);
const batch = {bookId:'a',stage:'actual',chapter:100,title:'宗门覆灭',source:'正文',items:[{type:'characters',id:hero.id,before:originalHero,value:'林逸突破金丹。',evidence:'林逸突破金丹。'},{type:'world',id:faction.id,before:'outdated',value:'青云宗被灭。',evidence:'青云宗被灭。'}]};
assert.throws(() => bridge.applyProgression(batch),/检查后发生了变化/);
assert.equal(JSON.stringify(bookHero),originalHero,'A failed batch must not mutate earlier cards');
assert.equal(JSON.stringify(bookFaction),originalFaction);
batch.items[1].before = originalFaction;
assert.equal(bridge.applyProgression(batch),2);
assert.ok(bookHero.currentState.includes('金丹'));
assert.ok(archive.list('world')[0].card.currentState.includes('被灭'));
assert.throws(() => bridge.applyProgression(batch),/检查后发生了变化/,'Replaying stale suggestions cannot overwrite adopted changes');
console.log('Progression: facts/plans, chapter boundaries, initial facts, history, idempotence, validation, entity evidence, archive retention and book isolation passed.');
console.log('Adoption bridge: atomic batch, stale-card guard, archive synchronization and duplicate-apply guard passed.');
